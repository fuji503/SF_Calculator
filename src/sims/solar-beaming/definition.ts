function toSolarInputs(i: Inputs): SolarInputs {
  const num = (k: string) => Number(i[k])
  return {
    d_sun: num('d_sun'),
    I_sun_auto: Boolean(i.I_sun_auto),
    I_sun: num('I_sun'),
    atm_case: String(i.atm_case) as AtmCase,
    tau: num('tau'),
    z_sun: num('z_sun'),
    z_t: num('z_t'),
    D: num('D'),
    N: num('N'),
    is_concave: Boolean(i.is_concave),
    rho: num('rho'),
    sigma_slope: num('sigma_slope'),
    sigma_point: num('sigma_point'),
    d: num('d'),
    theta_i: num('theta_i'),
    solve: Boolean(i.solve),
    goal_by_irradiance: Boolean(i.goal_by_irradiance),
    solve_diameter: Boolean(i.solve_diameter),
    P_goal: num('P_goal'),
    E_goal: num('E_goal'),
  }
}
