import { Explanation, Formula, List, M, Section } from '../../components/explanation/parts.tsx'

/** 「太陽光集光・送光」の解説（仕様書3(検証版) §4、§7） */
export default function SolarBeamingExplanation() {
  return (
    <Explanation>
      <Section title="このシミュレータでわかること">
        <p>
          たくさんの反射鏡で太陽光を1か所に集めて送るとき、受光地点にどれだけ強い光が届くか（放射照度）と、光の当たる範囲（スポット）の大きさを計算します。
          宇宙で集めて宇宙へ送る場合のほか、鏡や受光地点が地表にある場合の大気による減衰も扱います。
          これにより、太陽炉として光を集めて高温を得る、夜側や日陰にいる太陽電池パネルに光を送って発電させる、遠くの宇宙機に光を送る、などの計算ができます。
        </p>
      </Section>

      <Section title="計算の流れ">
        <p>1. 鏡の位置での太陽の強さと、太陽の見かけの大きさ（視直径）を、太陽からの距離で決めます。</p>
        <Formula tex="I_\odot = \frac{1361\ \mathrm{W/m^2}}{d_{sun}^2},\qquad \theta_\odot = \frac{9.30\ \mathrm{mrad}}{d_{sun}}">
          <M t="d_{sun}" /> は AU 単位。太陽から遠いほど、光は弱く、太陽は小さく見えます。
        </Formula>
        <p>
          2. 反射した光は、太陽の見かけの大きさの分だけ広がります。鏡の面のゆがみ（面精度）と向きのずれ（指向精度）があると、さらに広がります。
          誤差は 1σ で入力し、反射光の広がり（直径）は 8σ 相当として足し合わせます（法線が σ ずれると反射光は 2σ ずれ、直径でその4倍）。
        </p>
        <Formula tex="\theta_{eff} = \sqrt{\theta_\odot^2 + (8\sigma_{slope})^2 + (8\sigma_{point})^2}" />
        <Formula tex="D_{spot} = \begin{cases} d\,\theta_{eff} & (\text{凹面鏡}) \\ D + d\,\theta_{eff} & (\text{平面鏡}) \end{cases}">
          平面鏡は光を集められないので、スポットは鏡の口径 <M t="D" /> より小さくなりません。
        </Formula>
        <p>3. 鏡で受けた光のうち、反射率・入射角・大気で減った残りが、スポットに届きます（エネルギーの保存）。</p>
        <Formula tex="P_{spot} = \rho\, I_\odot\, A_{total} \cos\theta_i\, T_{atm},\qquad E_{target} = \frac{P_{spot}}{\pi D_{spot}^2/4}">
          <M t="A_{total}" /> は鏡の総面積、<M t="\theta_i" /> は鏡への入射角。大気を通る場合は <M t="T_{atm} = e^{-\tau/\cos z}" /> を通る回数だけ掛けます。
        </Formula>
        <p>4. どれだけ鏡を増やしても、太陽の表面より明るくはできません（熱力学の限界）。これを超える結果はエラーにします。</p>
        <Formula tex="E_{max} = \rho\, \pi L_\odot\, T_{atm} \approx 6.3\times10^{7}\ \mathrm{W/m^2}\ (\rho = 1)">
          <M t="L_\odot" /> は太陽の輝度（距離によらず一定）。1 AU の太陽光の約 46,000 倍に当たります。
        </Formula>
      </Section>

      <Section title="結果の読み方">
        <List
          items={[
            <>「太陽定数比（Suns）」は、届く光が鏡の位置の太陽光の何倍かを表します。平面鏡1枚では 1 倍を超えません。</>,
            <>遠くに送るほど、スポットは距離に比例して大きくなり、放射照度は距離の2乗に反比例して下がります。</>,
            <>精度の値は小さいほど高精度です。目安：100 µrad は、100 m 先で 1 cm ずれる角度です。</>,
            <>
              グラフの例：X軸を「鏡から受光体までの距離」、Y軸を「到達放射照度」にすると、どこまで送れるかが分かります。X軸を「基数」にすると、必要な鏡の数が分かります。
            </>,
          ]}
        />
      </Section>

      <Section title="計算に含めないもの">
        <List
          items={[
            '送光が成立している瞬間の値だけを計算します。受光体が動くときの照射できる時間や、鏡の首振りの速さは扱いません。',
            '受光体の大きさに応じて受け取る電力や熱は計算しません（スポット全体の電力と、単位面積あたりの値まで）。',
            '鏡同士の影や遮り、太陽の周縁減光、凹面鏡の収差、大気の揺らぎと屈折。',
          ]}
        />
      </Section>

      <Section title="計算の確かめ方">
        <p>
          仕様書のテストケース（1 AU の凹面鏡、平面鏡、1.52 AU の鏡1万枚、鏡が地表の場合など）で、期待値と有効数字4桁で一致することを確かめています。
          遠方で誤差がない場合は、従来の式 <M t="\rho L A\cos\theta_i/d^2" /> と一致します。
        </p>
      </Section>
    </Explanation>
  )
}
