    const outputs: Record<string, OutputValue> = {}
    if (r.outputs) {
      for (const [k, v] of Object.entries(r.outputs)) {
        if (typeof v === 'number') outputs[k] = { kind: 'number', value: v }
      }
    }
    return { outputs, warnings: r.warnings, errors: r.errors }
