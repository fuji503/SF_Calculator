function toLaserInputs(i: Inputs): LaserInputs {
  const num = (k: string) => Number(i[k])
  return {
    laser_type: String(i.laser_type) as LaserType,
    lambda: num('lambda'),
    D: num('D'),
    M2: num('M2'),
    sigma_jitter: num('sigma_jitter'),
    eta: num('eta'),
    E_chem: num('E_chem'),
    f_exhaust: num('f_exhaust'),
    k_aux: num('k_aux'),
    d_sun: num('d_sun'),
    I_sun_auto: Boolean(i.I_sun_auto),
    I_sun: num('I_sun'),
    P_opt: num('P_opt'),
    d: num('d'),
    atmosphere: String(i.atmosphere) as Atmosphere,
    placement: String(i.placement) as Placement,
    tau: num('tau'),
    z: num('z'),
    theta_turb: num('theta_turb'),
  }
}
