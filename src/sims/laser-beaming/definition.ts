/** 大気を通るときの τ のプリセット（発振器の方式と大気の組み合わせで決まる） */
function tauPreset(type: string, atmosphere: string): Inputs {
  if (atmosphere === 'vacuum') return {}
  return { tau: TAU_PRESETS[atmosphere as Exclude<Atmosphere, 'vacuum'>][type as LaserType] }
}

